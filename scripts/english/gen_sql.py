#!/usr/bin/env python3
"""Builds supabase/migrations/20240126000000_english_tests.sql from the test definitions.

    python3 scripts/english/gen_sql.py

The migration is idempotent: tests are upserted by test_type and their sections,
questions and answers are rebuilt on every run.
"""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
import mocks_ielts, mocks_other, drills

TESTS = mocks_ielts.TESTS + mocks_other.TESTS + drills.TESTS
OUT = os.path.join(os.path.dirname(__file__), '..', '..', 'supabase', 'migrations', '20240126000000_english_tests.sql')


def lit(s):
    if s is None:
        return 'NULL'
    assert '$q$' not in s, s[:40]
    return '$q$' + s + '$q$'


def validate(t):
    assert len(t['test_type']) <= 50 and len(t['level']) <= 10, t['test_type']
    for s in t['sections']:
        assert s['qs'], (t['test_type'], s['key'])
        for q in s['qs']:
            assert len(set(q['opts'])) == len(q['opts']), ('dup options', q['text'])


import random
from lib import TFNG, YNNG


def shuffled(q):
    """Deterministic shuffle so the right answer isn't usually option B (T/F/NG and Y/N/NG keep their order)."""
    if q['opts'] in (TFNG, YNNG):
        return q['opts'], q['correct']
    rnd = random.Random(q['text'])
    idx = list(range(len(q['opts'])))
    rnd.shuffle(idx)
    return [q['opts'][i] for i in idx], idx.index(q['correct'])


def total_q(t):
    return sum(len(s['qs']) for s in t['sections'])


def emit(t):
    validate(t)
    o = []
    kind = 'essay' if t['essay'] else 'quiz'
    o.append(f"-- {t['title']}")
    o.append("DO $ep$ DECLARE v_test UUID; v_sec UUID; v_q UUID; BEGIN")
    o.append(f"""  INSERT INTO public.tests (title, description, test_type, track, level, duration_minutes,
      total_questions, passing_score, is_active, is_skill_practice, skill, content_kind)
  VALUES ({lit(t['title'])}, {lit(t['desc'])}, {lit(t['test_type'])}, 'en', {lit(t['level'])}, {t['minutes']},
      {total_q(t)}, {t['passing']}, TRUE, {'TRUE' if t['is_skill_practice'] else 'FALSE'}, {lit(t['skill'])}, {lit(kind)})
  ON CONFLICT (test_type) DO UPDATE SET title = EXCLUDED.title, description = EXCLUDED.description,
      track = 'en', level = EXCLUDED.level, duration_minutes = EXCLUDED.duration_minutes,
      total_questions = EXCLUDED.total_questions, passing_score = EXCLUDED.passing_score,
      is_active = TRUE, is_skill_practice = EXCLUDED.is_skill_practice, skill = EXCLUDED.skill,
      content_kind = EXCLUDED.content_kind
  RETURNING id INTO v_test;""")
    o.append("  DELETE FROM public.test_sections WHERE test_id = v_test;")
    o.append("  DELETE FROM public.test_writing_prompts WHERE test_id = v_test;")
    for si, s in enumerate(t['sections']):
        o.append(f"""  INSERT INTO public.test_sections (test_id, key, name, type, official_duration_minutes, instructions, passage, audio_url, order_index)
  VALUES (v_test, {lit(s['key'])}, {lit(s['name'])}, {lit(s['type'])}, {s['minutes'] or 'NULL'}, {lit(s['instr'])}, {lit(s['passage'])}, NULL, {si})
  RETURNING id INTO v_sec;""")
        for qi, q in enumerate(s['qs']):
            o.append(f"""  INSERT INTO public.test_questions (test_id, section_id, question_text, question_type, points, explanation, order_index)
  VALUES (v_test, v_sec, {lit(q['text'])}, 'multiple_choice', 1, {lit(q['why'])}, {qi}) RETURNING id INTO v_q;""")
            opts, correct = shuffled(q)
            vals = ",\n    ".join(
                f"(v_q, {lit(a)}, {'TRUE' if ai == correct else 'FALSE'}, {ai})" for ai, a in enumerate(opts))
            o.append(f"  INSERT INTO public.test_answers (question_id, answer_text, is_correct, order_index) VALUES\n    {vals};")
    w = t['writing']
    if w:
        o.append(f"""  INSERT INTO public.test_writing_prompts (test_id, name, official_duration_minutes, instructions, prompt, sample_answer)
  VALUES (v_test, {lit(w['name'])}, {w['minutes']}, {lit(w['instr'])}, {lit(w['prompt'])}, {lit(w['sample'])});""")
    o.append("END $ep$;\n")
    return "\n".join(o)


header = """-- English test library (track = 'en'): IELTS Academic + General Training, TOEFL iBT,
-- TOEIC, Cambridge B2 First, a placement test, and quick skill-practice drills.
--
-- Generated by scripts/english/gen_sql.py -- edit the Python files there, not this SQL.
-- Safe to run more than once: tests are upserted by test_type and rebuilt.
-- All content is original practice material written for EuroPass Academy.

"""
seen = set()
for t in TESTS:
    assert t['test_type'] not in seen, t['test_type']
    seen.add(t['test_type'])
sql = header + "\n".join(emit(t) for t in TESTS)
open(OUT, 'w', encoding='utf-8').write(sql)
full = [t for t in TESTS if not t['is_skill_practice']]
print(len(TESTS), 'tests,', len(full), 'full mocks,', sum(total_q(t) for t in TESTS), 'questions ->', os.path.abspath(OUT))
